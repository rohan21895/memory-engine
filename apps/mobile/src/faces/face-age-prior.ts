/**
 * Is this face a young child? A logistic probe over the identity embedding.
 *
 * Not shipped for its own sake: it exists so babies and adults can be clustered
 * at DIFFERENT thresholds. Measured on Rohan's library, no single bar works --
 * at 0.40 Aastha lands in one tile but two of the children (Ved and Krishiv)
 * weld into one person, and at 0.46 the children separate but Aastha shatters
 * into eight. Splitting the bar by age fixed both at once: every one of the four
 * verified people landed in exactly one tile with zero fusions.
 *
 * Trained on 414 baby faces and 3882 adult faces from identities Rohan confirmed
 * himself (avika, krishiv, ved). Scored by leaving whole IDENTITIES out, not
 * random faces, so it measures recognising a child it has never seen: 90.9%.
 *
 * ERRORS ARE NOT SYMMETRIC. Calling an adult a baby costs a tighter bar and a
 * split, which a merge question repairs. Calling a baby an adult hands it the
 * loose bar and risks fusing two children, which nothing repairs. So the cut is
 * deliberately far below 0.5 -- measured at 0.05, treating 17% of faces as
 * children, which cost nothing (still one tile each, zero fusions, and slightly
 * FEWER same-photo violations).
 *
 * The weights belong to the w600k_mbf embedding space. A model change invalidates
 * them exactly as it invalidates the clustering thresholds.
 */
