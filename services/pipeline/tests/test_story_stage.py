class NoProxyGenerator(unittest.TestCase):
    def test_an_unbuilt_ingest_worker_is_unavailable_not_empty(self):
        """A library full of video and no way to decode it is not "no moments".

        UNAVAILABLE and SKIPPED are different answers and only one of them means
        the library is finished. Pointing the runner at a repo root with no
        built worker in it is the same condition a fresh checkout is in.
        """
        require_ingest_binary()
        require_ffmpeg()
        root = Path(tempfile.mkdtemp(prefix="mep-story-nobin-"))
        workdir = Path(tempfile.mkdtemp(prefix="mep-story-nobin-work-"))
        empty_root = Path(tempfile.mkdtemp(prefix="mep-story-nobin-repo-"))
        try:
            write_clip(root / "VID_0001.mp4", seconds=1.0, rate=30)
            report = run_pipeline(
                [root],
                workdir,
                stages=["ingest", "story"],
                settings=Settings(render_print=False, render_video=False),
            )
            self.assertEqual(StageStatus.COMPLETED, _stage(report, "ingest").status)

            blind = run_pipeline(
                [root],
                workdir,
                stages=["story"],
                settings=Settings(render_print=False, render_video=False),
                repo_root=empty_root,
            )
            story = _stage(blind, "story")
            self.assertEqual(StageStatus.UNAVAILABLE, story.status, story.detail)
            self.assertIn("cargo build", story.detail)
        finally:
            for path in (root, workdir, empty_root):
                shutil.rmtree(path, ignore_errors=True)


