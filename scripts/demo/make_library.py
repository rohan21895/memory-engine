def write_broken(out: Path, healthy_jpeg: bytes,
                 healthy_mp4: bytes) -> list[dict[str, Any]]:
    """Files that must fail LOUDLY.

    "Loudly" is the whole point. A pipeline that skips a corrupt file without
    saying so loses a photograph and reports success; the ingest worker
    quarantines instead, and a demo has to be able to check that it did.
    """
    entries: list[dict[str, Any]] = []
    folder = out / "Broken"
    folder.mkdir(parents=True, exist_ok=True)
    stamp = epoch(datetime(2023, 6, 12, 23, 0, 0))

    # Two truncated JPEGs, at two depths, because one of them is a POSITIVE
    # CONTROL and the other is the case that actually matters.
    #
    # 512 bytes stops before the start-of-scan marker, so no decoder can even
    # begin, and the ingest worker quarantines it. That is the control: if this
    # one is not quarantined, quarantine is broken outright and every other
    # result here is suspect.
    #
    # A third of the file has the full header and a third of the entropy data.
    # The Rust `image` crate decodes it anyway and returns a partly-grey
    # picture, so at the time of writing the ingest worker files it as
    # state=proxied with a pHash and a thumbnail -- a mangled photograph
    # entering the library indistinguishable from a good one. The contract says
    # otherwise: contracts/fixtures/media-record/valid/file-truncated-quarantined.json
    # is quarantined with kind=unknown. The expectation below is the contract's,
    # so a consumer that checks it reports a real defect rather than agreeing
    # with the bug.
    (folder / "IMG_HEADER_ONLY.JPG").write_bytes(healthy_jpeg[:512])
    entries.append({
        "relpath": "Broken/IMG_HEADER_ONLY.JPG",
        "kind": "broken",
        "expect": "quarantine",
        "expect_detail": "512 bytes: truncated before the start-of-scan marker",
        "control": "positive",
        "note": "positive control -- if this is not quarantined, quarantine is broken",
    })
    (folder / "IMG_TRUNCATED.JPG").write_bytes(
        healthy_jpeg[: max(2048, len(healthy_jpeg) // 3)]
    )
    entries.append({
        "relpath": "Broken/IMG_TRUNCATED.JPG",
        "kind": "broken",
        "expect": "quarantine",
        "expect_detail": "one third of a JPEG: header parses, most scan data is gone",
        "known_gap": (
            "workers/ingest decodes with the `image` crate, which tolerates "
            "this and yields a partly-grey picture; the record comes back "
            "state=proxied instead of quarantined"
        ),
        "note": "the case that matters: silently accepted today",
    })

    # A zero-byte file, which is what an interrupted copy leaves behind.
    (folder / "IMG_ZERO_BYTES.JPG").write_bytes(b"")
    entries.append({
        "relpath": "Broken/IMG_ZERO_BYTES.JPG",
        "kind": "broken",
        "expect": "quarantine",
        "expect_detail": "zero bytes",
        "note": "what an interrupted copy leaves behind",
    })

    # An MP4 cut after the header: ftyp is present so it is detected as video,
    # but no decoder can open it. Ingest only hashes videos, so this one has to
    # fail at the proxy stage rather than at scan.
    (folder / "VID_TRUNCATED.MP4").write_bytes(healthy_mp4[: min(8192, len(healthy_mp4))])
    entries.append({
        "relpath": "Broken/VID_TRUNCATED.MP4",
        "kind": "broken",
        "expect": "proxy_failure",
        "expect_detail": "ftyp present, moov absent; scan hashes it, proxy must fail",
        "note": "ingest does not decode video at scan time, so this survives scan",
    })

    # Strays every real library has.
    (folder / "notes.txt").write_text(
        "Not media. Every real library has one of these.\n", encoding="utf-8"
    )
    entries.append({
        "relpath": "Broken/notes.txt",
        "kind": "stray",
        "expect": "quarantine",
        "expect_detail": "unsupported format (no recognised signature)",
        "note": "a stray text file",
    })
    (folder / "IMG_SIDECAR.xmp").write_text(
        '<?xml version="1.0"?><x:xmpmeta xmlns:x="adobe:ns:meta/"/>\n', encoding="utf-8"
    )
    entries.append({
        "relpath": "Broken/IMG_SIDECAR.xmp",
        "kind": "stray",
        "expect": "quarantine",
        "expect_detail": "unsupported format (XMP sidecar)",
        "note": "sidecar with no adopting parent in this folder",
    })

    for entry in entries:
        os.utime(out / entry["relpath"], (stamp, stamp))
    return entries


