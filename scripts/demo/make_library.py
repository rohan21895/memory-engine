def check_destination(out: Path, force: bool) -> None:
    """Refuse destinations that could contain, or be mistaken for, real media.

    Writing a synthetic library *into* a real photo folder is the exact
    accident this script exists to prevent, and `--force` would then delete
    real files.
    """
    resolved = out.expanduser().resolve()

    reason = real_media_location(resolved)
    if reason is not None:
        raise SystemExit(
            f"refusing to write into {resolved}: {reason}.\n"
            "  pick a scratch directory, e.g. --out /tmp/demo-library"
        )

    if not resolved.exists():
        return
    if not resolved.is_dir():
        raise SystemExit(f"--out exists and is not a directory: {resolved}")

    entries = [p for p in resolved.iterdir() if p.name != ".DS_Store"]
    if not entries:
        return
    if not (resolved / MANIFEST_NAME).is_file():
        raise SystemExit(
            f"{resolved} is not empty and has no {MANIFEST_NAME}, so it was not "
            "generated by this script.\n"
            "  refusing to touch it -- pick an empty directory."
        )
    if not force:
        raise SystemExit(
            f"{resolved} already holds a generated library. Pass --force to replace it."
        )


# ---------------------------------------------------------------------------
# Deterministic randomness
# ---------------------------------------------------------------------------


def stream(seed: int, *labels: object) -> random.Random:
    """An independent RNG stream, named rather than positional.

    One shared Random() would make every value depend on the order everything
    else was generated in, so adding a photo to event A would change every
    pixel of event D and every media_id in the library. Naming the stream keeps
    a file's bytes a function of that file's identity alone.
    """
    key = "\x1f".join([str(seed), *(str(label) for label in labels)])
    digest = hashlib.blake2b(key.encode("utf-8"), digest_size=8).digest()
    return random.Random(int.from_bytes(digest, "big"))


