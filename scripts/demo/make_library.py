def exif_bytes(*, captured_local: str | None, utc_offset: str | None,
               make: str, model: str,
               lens: str | None, orientation: int) -> bytes | None:
    """Build an EXIF block, or None for a still that must have no EXIF at all.

    Returning None rather than an empty block matters: the ingest worker
    distinguishes "EXIF present but undated" from "no EXIF", and a stray empty
    IFD would make the no-date case untestable.
    """
    if captured_local is None and orientation == 1 and not make:
        return None
    exif = Image.Exif()
    if make:
        exif[TAG_MAKE] = make
    if model:
        exif[TAG_MODEL] = model
    exif[TAG_ORIENTATION] = orientation
    exif[TAG_SOFTWARE] = "memory-engine make_library.py (synthetic)"
    if captured_local is not None:
        exif[TAG_DATETIME] = captured_local
        sub = exif.get_ifd(TAG_EXIF_IFD)
        sub[TAG_DATETIME_ORIGINAL] = captured_local
        sub[TAG_DATETIME_DIGITIZED] = captured_local
        # The offset only means anything alongside a date, so it is written
        # inside this branch. A camera that writes neither leaves the reading
        # zoneless, which is a real state the pipeline must keep distinguishing
        # from "no EXIF at all" and from "dated with a zone".
        if utc_offset:
            sub[TAG_OFFSET_TIME_ORIGINAL] = utc_offset
            sub[TAG_OFFSET_TIME_DIGITIZED] = utc_offset
        if lens:
            sub[TAG_LENS_MODEL] = lens
    return exif.tobytes()


def write_still(path: Path, image: Image.Image, *, exif: bytes | None,
                quality: int, mtime: float) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    kwargs: dict[str, Any] = {"quality": quality, "optimize": True, "progressive": False}
    if exif is not None:
        kwargs["exif"] = exif
    image.save(path, "JPEG", **kwargs)
    os.utime(path, (mtime, mtime))


