def blake3_hex(path: Path) -> str:
    """The media_id the ingest worker will derive for this file.

    Plain BLAKE3 over the file bytes -- see `read_source_once` in
    workers/ingest/src/media.rs. Recording it here lets a consumer assert
    against identities instead of matching on filenames, which is what makes
    the expectations below checkable rather than decorative.
    """
    try:
        import blake3
    except ImportError:
        return ""
    hasher = blake3.blake3()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


def reconcile(out: Path, files: Sequence[dict[str, Any]]) -> None:
    """Fail if the manifest and the directory disagree in any direction.

    Three separate ways to lie, all of which have to be impossible:
      * a manifest entry with no file  -- something overwrote or deleted it
      * a file with no manifest entry  -- something wrote outside the plan
      * a recorded BLAKE3 that no longer matches the bytes -- a later write
        landed on an earlier file's path, which is the collision case
    """
    expected = {
        entry["relpath"]: entry for entry in files if entry.get("generated", True)
    }
    on_disk = {
        str(path.relative_to(out)) for path in out.rglob("*")
        if path.is_file() and path.name != MANIFEST_NAME
    }

    problems: list[str] = []
    if len(expected) != len([e for e in files if e.get("generated", True)]):
        problems.append("duplicate relpaths in the plan")
    for missing in sorted(set(expected) - on_disk):
        problems.append(f"manifest lists {missing}, which is not on disk")
    for extra in sorted(on_disk - set(expected)):
        problems.append(f"{extra} is on disk but not in the manifest")
    for relpath, entry in sorted(expected.items()):
        digest = entry.get("blake3")
        if not digest or relpath not in on_disk:
            continue
        actual = blake3_hex(out / relpath)
        if actual and actual != digest:
            problems.append(
                f"{relpath} hashes to {actual[:12]} but the manifest says {digest[:12]}"
            )

    if problems:
        raise SystemExit(
            "generated library does not match its own manifest:\n  "
            + "\n  ".join(problems[:20])
            + (f"\n  ... and {len(problems) - 20} more" if len(problems) > 20 else "")
        )


