def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--out", type=Path, required=True, help="destination directory")
    parser.add_argument("--seed", type=int, default=20260817)
    parser.add_argument("--stills", type=int, default=200)
    parser.add_argument("--clips", type=int, default=10)
    parser.add_argument("--force", action="store_true",
                        help="replace an existing generated library")
    parser.add_argument("--ffmpeg", default=os.environ.get("MEMORY_ENGINE_FFMPEG", "ffmpeg"))
    parser.add_argument("--no-video", action="store_true",
                        help="stills only; the manifest records the clips as NOT GENERATED")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    out = args.out.expanduser().resolve()
    check_destination(out, args.force)

    def say(message: str) -> None:
        if not args.quiet:
            print(message, flush=True)

    ffmpeg = shutil.which(args.ffmpeg) if not args.no_video else None
    video_skipped_reason = None
    if args.no_video:
        video_skipped_reason = "--no-video was passed"
    elif ffmpeg is None:
        # Not a warning buried in the output: the library is materially
        # different without clips, and the manifest has to say so.
        video_skipped_reason = f"ffmpeg not found on PATH (looked for {args.ffmpeg!r})"

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    files: list[dict[str, Any]] = []

    # --- stills ----------------------------------------------------------
    planned = plan_stills(args.seed, args.stills)
    say(f"  stills   {len(planned)} ...")
    scene_cache: dict[str, Scene] = {}
    for position, still in enumerate(planned):
        if still.burst_id:
            base = scene_cache.get(still.burst_id)
            if base is None:
                base = build_scene(
                    stream(args.seed, "burst", still.burst_id),
                    still.event.palette, still.subjects,
                )
                scene_cache[still.burst_id] = base
            scene = jittered(
                base, still.burst_frame,
                stream(args.seed, "burst-jitter", still.burst_id, still.burst_frame),
            )
        else:
            scene = build_scene(
                stream(args.seed, "scene", still.relpath),
                still.event.palette, still.subjects,
            )
        image = render(scene, *still.size)
        exif = (
            exif_bytes(
                captured_local=still.captured_local,
                utc_offset=still.event.utc_offset,
                make=still.event.make, model=still.event.model,
                lens=still.event.lens, orientation=still.orientation,
            )
            if still.write_exif else None
        )
        path = out / still.relpath
        write_still(path, image, exif=exif, quality=still.quality,
                    mtime=epoch(still.mtime_dt))
        files.append({
            "relpath": still.relpath,
            "kind": "still",
            "blake3": blake3_hex(path),
            "byte_size": path.stat().st_size,
            "stored_size": {"width": still.size[0], "height": still.size[1]},
            "orientation": still.orientation,
            "event": still.event.key,
            "exif_datetime_original": still.captured_local,
            # None means the file carries a wall-clock reading with no zone, so
            # `captured_at.utc` MUST stay null on the resulting MediaRecord. A
            # consumer that finds a utc against a null offset here has found
            # the pipeline inventing a zone.
            "exif_offset_time_original": (
                still.event.utc_offset if still.captured_local else None
            ),
            "has_exif": exif is not None,
            "filesystem_mtime_utc": datetime.fromtimestamp(
                epoch(still.mtime_dt), timezone.utc
            ).isoformat().replace("+00:00", "Z"),
            "burst_id": still.burst_id,
            "tags": list(still.tags),
        })
        if not args.quiet and (position + 1) % 50 == 0:
            say(f"           {position + 1}/{len(planned)}")

    # --- clips -----------------------------------------------------------
    clip_specs = plan_clips(args.seed, args.clips)
    if video_skipped_reason:
        say(f"  clips    SKIPPED — {video_skipped_reason}")
        for spec in clip_specs:
            files.append({
                "relpath": spec.relpath,
                "kind": "clip",
                "generated": False,
                "skipped_reason": video_skipped_reason,
                "note": spec.note,
            })
    else:
        say(f"  clips    {len(clip_specs)} ...")
        for spec in clip_specs:
            scene = build_scene(
                stream(args.seed, "clip", spec.scene_key), spec.palette, spec.subjects
            )
            base = render(scene, spec.width * 2, spec.height * 2)
            path = out / spec.relpath
            encode_clip(ffmpeg, spec, base, path)
            files.append({
                "relpath": spec.relpath,
                "kind": "clip",
                "generated": True,
                "blake3": blake3_hex(path),
                "byte_size": path.stat().st_size,
                "stored_size": {"width": spec.width, "height": spec.height},
                "frame_rate": spec.rate_label,
                "duration_s": spec.duration,
                "has_audio": spec.audio,
                "start_timecode": spec.timecode,
                "note": spec.note,
            })

    # --- broken ----------------------------------------------------------
    # Truncations are taken from real generated bytes so the headers are real.
    healthy_jpeg = (out / planned[0].relpath).read_bytes()
    healthy_mp4 = b""
    if not video_skipped_reason:
        healthy_mp4 = (out / clip_specs[0].relpath).read_bytes()
    else:
        # Without ffmpeg there is no MP4 to truncate. Say so rather than
        # writing a fake one that would test the wrong failure.
        say("  broken   MP4 truncation SKIPPED — no clip was generated to truncate")
    broken = write_broken(out, healthy_jpeg, healthy_mp4)
    for entry in broken:
        if entry["relpath"].endswith(".MP4") and video_skipped_reason:
            entry["generated"] = False
            entry["skipped_reason"] = "no MP4 existed to truncate"
            entry["expect"] = "not_generated"
            (out / entry["relpath"]).unlink(missing_ok=True)
            continue
        path = out / entry["relpath"]
        entry["blake3"] = blake3_hex(path)
        entry["byte_size"] = path.stat().st_size
    files.extend(broken)

    # --- reconcile the plan against the disk -----------------------------
    # A manifest that describes files which are not there is worse than no
    # manifest: every consumer downstream asserts against a fiction. This is
    # the check that caught the filename collision above, so it stays.
    reconcile(out, files)

    # --- manifest --------------------------------------------------------
    by_relpath = {entry["relpath"]: entry for entry in files}

    bursts: dict[str, list[str]] = {}
    for entry in files:
        if entry.get("burst_id"):
            bursts.setdefault(entry["burst_id"], []).append(entry["relpath"])

    spans = [
        {
            "span_kind": "gopro_chapter",
            "family": "gx",
            "recording": "0012",
            "members": [f"GoPro/GX0{n + 1}0012.MP4" for n in range(3)],
            "expected_indexes": [0, 1, 2],
        },
        {
            "span_kind": "gopro_chapter",
            "family": "legacy",
            "recording": "0044",
            "members": ["GoPro/GOPR0044.MP4", "GoPro/GP010044.MP4"],
            "expected_indexes": [0, 1],
        },
    ]
    for span in spans:
        span["members"] = [m for m in span["members"] if m in by_relpath]
        span["member_blake3"] = [by_relpath[m].get("blake3", "") for m in span["members"]]
        span["generated"] = all(by_relpath[m].get("generated", True) for m in span["members"])

    generated_count = sum(1 for e in files if e.get("generated", True))
    manifest = {
        "generator": "scripts/demo/make_library.py",
        "generator_version": GENERATOR_VERSION,
        "seed": args.seed,
        "synthetic": True,
        "disclaimer": (
            "Every file here is drawn or encoded from scratch. The faces are "
            "cartoons and prove nothing about detection quality; no quality, "
            "aesthetic or face metric measured on this library is meaningful. "
            "See the module docstring of make_library.py."
        ),
        "counts": {
            "stills": sum(1 for e in files if e["kind"] == "still"),
            "clips": sum(1 for e in files if e["kind"] == "clip"),
            "clips_generated": sum(
                1 for e in files if e["kind"] == "clip" and e.get("generated")
            ),
            "broken": sum(1 for e in files if e["kind"] == "broken"),
            "strays": sum(1 for e in files if e["kind"] == "stray"),
            "files_on_disk": generated_count,
        },
        "skipped": ([] if not video_skipped_reason else [{
            "what": "video clips and the truncated MP4",
            "reason": video_skipped_reason,
            "consequence": (
                "no video, no GoPro spans, no frame-rate coverage, and the "
                "proxy stage has nothing to fail on"
            ),
        }]),
        "expectations": {
            "near_duplicate_bursts": [
                {"burst_id": burst, "members": sorted(members),
                 "member_blake3": [by_relpath[m]["blake3"] for m in sorted(members)]}
                for burst, members in sorted(bursts.items())
            ],
            "no_exif_date": [
                e["relpath"] for e in files if "no_exif_date" in e.get("tags", [])
            ],
            "unknown_capture_time": [
                e["relpath"] for e in files if "no_filename_date" in e.get("tags", [])
            ],
            "filename_dated": [
                e["relpath"] for e in files if "filename_dated" in e.get("tags", [])
            ],
            "exif_mtime_disagreement": [
                {
                    "relpath": e["relpath"],
                    "exif_datetime_original": e["exif_datetime_original"],
                    "filesystem_mtime_utc": e["filesystem_mtime_utc"],
                }
                for e in files if "exif_mtime_disagreement" in e.get("tags", [])
            ],
            "orientation_6": [
                e["relpath"] for e in files if "orientation_6" in e.get("tags", [])
            ],
            "gopro_spans": spans,
            "must_quarantine": [
                {
                    "relpath": e["relpath"],
                    "why": e["expect_detail"],
                    **({"control": e["control"]} if e.get("control") else {}),
                    **({"known_gap": e["known_gap"]} if e.get("known_gap") else {}),
                }
                for e in files if e.get("expect") == "quarantine"
            ] + [
                # The manifest sits inside the library so a consumer can find
                # it without being told where it is. The scanner therefore
                # walks it, cannot identify it, and quarantines it -- which is
                # correct behaviour and is declared here so it does not read as
                # an unexplained extra quarantine.
                {"relpath": MANIFEST_NAME,
                 "why": "the manifest itself: not media, no recognised signature"}
            ],
            "must_fail_at_proxy": [
                {"relpath": e["relpath"], "why": e["expect_detail"]}
                for e in files if e.get("expect") == "proxy_failure"
            ],
            "frame_rates": sorted({
                e["frame_rate"] for e in files if e.get("frame_rate")
            }),
            "vertical_clips": [
                e["relpath"] for e in files
                if e.get("kind") == "clip" and e.get("generated")
                and e["stored_size"]["height"] > e["stored_size"]["width"]
            ],
            "silent_clips": [
                e["relpath"] for e in files
                if e.get("kind") == "clip" and e.get("generated") and not e["has_audio"]
            ],
        },
        "not_represented": [
            "real photographic content of any kind",
            "real faces -- the drawn ones are cartoons (see disclaimer)",
            "HEIC/HEIF, RAW, Live Photos, or any Apple/Android container",
            "real sensor noise, motion blur, lens character, JPEG generation loss",
            "GPS, altitude, or any location metadata",
            "audio worth analysing: the tracks are sine tones, not music or speech",
            "hardware-encoder quirks: everything is libx264 at one preset",
            "libraries at scale -- 200 stills is not 3TB, and nothing here "
            "exercises the resumable-scan or I/O-saturation paths",
        ],
        "files": files,
    }
    (out / MANIFEST_NAME).write_text(
        json.dumps(manifest, indent=2, sort_keys=False) + "\n", encoding="utf-8"
    )

    counts = manifest["counts"]
    say("")
    say(f"  library  {out}")
    say(f"           {counts['stills']} stills, "
        f"{counts['clips_generated']}/{counts['clips']} clips, "
        f"{counts['broken']} broken, {counts['strays']} strays")
    if manifest["skipped"]:
        for skip in manifest["skipped"]:
            say(f"  SKIPPED  {skip['what']} — {skip['reason']}")
            say(f"           consequence: {skip['consequence']}")
        say("  NOT a complete library. Exit code 2.")
        return 2
    say(f"  manifest {out / MANIFEST_NAME}")
    return 0


