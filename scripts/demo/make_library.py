#!/usr/bin/env python3
"""Generate a synthetic photo-and-video library for exercising the pipeline.

WHAT THIS LIBRARY IS NOT
========================
Nothing in it is a photograph. Every still is drawn procedurally with PIL from
a seeded RNG, and every clip is encoded by FFmpeg from one of those drawings.

The "faces" are cartoons: a skin-coloured oval, two eye ellipses with pupils,
brows, a nose line and a mouth arc. They exist so the face stack has something
with roughly face-shaped structure to run against, and so a *plumbing* failure
-- a detector that is never actually called, a BGR/RGB swap, a resize
convention mismatch, a post-processing step that returns an empty tensor --
shows up as a crash or an obviously wrong count instead of as silence.

THEY PROVE NOTHING ABOUT DETECTION QUALITY. A detector that finds all of them
may find no real faces, and a detector that finds none of them may be excellent
on real ones. Any recall/precision number measured on this library is
meaningless and must never reach a model card, an eval report, or a regression
gate. Real numbers come from `packages/eval-harness/` run against a consented
benchmark library of real photographs.

The same caveat applies, less obviously, to everything else here. Synthetic
stills have clean exposure, no motion blur, no chroma noise from a real sensor,
no lens character and no JPEG generation loss. Quality scores, aesthetic
scores and dedupe thresholds tuned against this library will not transfer.

WHAT IT IS FOR
==============
The user's own photographs are not a test fixture. Exercising the pipeline
must never require pointing it at a real photo folder, and `~/Downloads` is
explicitly off limits. This produces a library that is *hostile in the ways
that matter* so the pipeline can be run end to end on a machine that has never
seen a real image:

  * near-duplicate bursts (the same scene five times, barely varied) -- the
    thing dedupe exists for, and the thing a too-generous Hamming threshold
    silently over-merges
  * a still with no EXIF date at all, and a filename that matches no date
    pattern, so it must come out `precision: unknown` rather than at the epoch
  * stills whose EXIF date and filesystem mtime disagree by years -- the
    "copied off an old hard drive" case, where trusting mtime reorders a
    library
  * a GoPro chaptered recording spanning files (GX010012 / GX020012 / ...),
    matching `workers/ingest/src/gopro.rs` exactly, plus a legacy
    GOPR0044 / GP010044 pair, which uses a *different* index convention
  * a vertical clip and horizontal clips, at 24, 25, 29.97, 30 and 60 fps
  * a truncated JPEG, a truncated MP4 and a zero-byte file, which must fail
    loudly and be quarantined -- never silently skipped
  * an EXIF-orientation-6 still, whose oriented size is the transpose of its
    stored size
  * unsupported strays (a .txt, an .xmp sidecar) of the kind every real
    library contains

Everything is deterministic from `--seed`: same seed, same bytes, same BLAKE3,
same media_ids. The manifest records the BLAKE3 of every file, which is exactly
the `media_id` the ingest worker will derive, so a consumer can assert against
identities rather than guessing from filenames.

Usage:
    python3 scripts/demo/make_library.py --out /tmp/demo-library
    python3 scripts/demo/make_library.py --out DIR --seed 7 --stills 200 --clips 10
"""

