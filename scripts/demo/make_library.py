@dataclass(frozen=True)
class ClipSpec:
    relpath: str
    width: int
    height: int
    rate: str                  # ffmpeg rate expression, e.g. "30000/1001"
    rate_label: str            # human label, e.g. "29.97"
    duration: float
    scene_key: str
    palette: str
    subjects: int
    timecode: str | None = None
    audio: bool = True
    tone_hz: int = 330
    captured_local: str | None = None
    mtime: float = 0.0
    note: str = ""


def encode_clip(ffmpeg: str, spec: ClipSpec, base: Image.Image, dest: Path) -> None:
    """Encode one clip by panning across a still we drew.

    Panning a 2x drawing is not cinematography, but it produces real inter-frame
    motion, real P-frames and a real variable bitrate, which is what the proxy
    pipeline and any motion signal actually consume. A static image would encode
    to almost nothing and hide every bug that only appears with motion.

    `-fflags +bitexact -flags:v +bitexact` is what makes the output reproducible:
    without it FFmpeg stamps the muxer version and a wall-clock creation time
    into the container, the BLAKE3 changes on every run, and every media_id in
    the library churns.
    """
    dest.parent.mkdir(parents=True, exist_ok=True)
    staging = dest.parent / f".{dest.name}.base.png"
    base.save(staging, "PNG")

    pan = f"(iw-ow)*min(1\\,t/{spec.duration:.3f})"
    tilt = f"(ih-oh)*(0.5+0.35*sin(2*PI*t/{max(spec.duration, 0.001):.3f}))"
    video_filter = (
        f"scale={spec.width * 2}:{spec.height * 2}:flags=bicubic,"
        f"crop={spec.width}:{spec.height}:'{pan}':'{tilt}',"
        f"format=yuv420p"
    )

    command = [
        ffmpeg, "-y", "-hide_banner", "-loglevel", "error", "-nostdin",
        "-loop", "1", "-framerate", spec.rate, "-t", f"{spec.duration}", "-i", str(staging),
    ]
    if spec.audio:
        command += [
            "-f", "lavfi",
            "-i", f"sine=frequency={spec.tone_hz}:sample_rate=48000:duration={spec.duration}",
        ]
    command += [
        "-vf", video_filter,
        "-r", spec.rate,
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "26",
        "-pix_fmt", "yuv420p", "-g", "30",
    ]
    if spec.audio:
        command += ["-c:a", "aac", "-b:a", "96k", "-ar", "48000", "-ac", "1", "-shortest"]
    if spec.timecode:
        command += ["-timecode", spec.timecode]
    command += [
        "-fflags", "+bitexact", "-flags:v", "+bitexact",
        "-movflags", "+faststart",
        "-map_metadata", "-1",
        str(dest),
    ]

    result = subprocess.run(command, capture_output=True, text=True)
    staging.unlink(missing_ok=True)
    if result.returncode != 0:
        raise SystemExit(
            f"ffmpeg failed for {spec.relpath} (exit {result.returncode}):\n"
            f"{result.stderr.strip()}"
        )
    os.utime(dest, (spec.mtime, spec.mtime))


