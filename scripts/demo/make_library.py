@dataclass(frozen=True)
class Event:
    key: str
    # Short filename code. MUST be unique across events, including events that
    # share a folder -- two events in one folder generating IMG_GO0006.JPG each
    # means the second silently overwrites the first, and the only visible
    # symptom is a file count that nobody checks. `plan_stills` asserts it.
    code: str
    folder: str
    palette: str
    start: datetime
    interval_s: int
    make: str
    model: str
    lens: str | None
    weight: int          # share of the filler stills
    # The zone this camera stamped alongside DateTimeOriginal, or None for a
    # body that writes none. Every event here happened in India, so a camera
    # that writes an offset writes "+05:30"; the 2019 Canon does not, because
    # OffsetTimeOriginal is EXIF 2.31 and plenty of bodies of that generation
    # never wrote it. That asymmetry is the point: a library where every file
    # is dated cannot exercise the code that refuses to invent a zone.
    utc_offset: str | None = None


