@dataclass(frozen=True)
class Scene:
    """Everything that decides what one drawing looks like.

    A near-duplicate burst is five Scenes that differ only in `jitter`.
    """

    palette: str
    horizon: float            # 0..1, fraction of height
    sun_x: float              # 0..1
    sun_r: float              # fraction of width
    ridge_seed: int
    subjects: tuple[tuple[float, float, float, int, int, int], ...]
    # (x, y_base, scale, skin_idx, hair_idx, shirt_idx)
    grain: int
    jitter: tuple[float, float, float] = (0.0, 0.0, 0.0)  # dx, dy, brightness


def build_scene(rng: random.Random, palette: str, subject_count: int) -> Scene:
    horizon = rng.uniform(0.34, 0.66)
    subjects = []
    for index in range(subject_count):
        subjects.append((
            rng.uniform(0.12, 0.88),
            rng.uniform(horizon + 0.05, 0.95),
            rng.uniform(0.10, 0.26),
            rng.randrange(len(SKIN_TONES)),
            rng.randrange(len(HAIR_TONES)),
            rng.randrange(len(SHIRT_TONES)),
        ))
    return Scene(
        palette=palette,
        horizon=horizon,
        sun_x=rng.uniform(0.08, 0.92),
        sun_r=rng.uniform(0.03, 0.11),
        ridge_seed=rng.randrange(1 << 30),
        subjects=tuple(subjects),
        grain=rng.randrange(1 << 30),
    )


def jittered(scene: Scene, index: int, rng: random.Random) -> Scene:
    """One frame of a burst: the same scene, moved a hair.

    The magnitudes are small on purpose. A burst that varies a lot is not a
    burst, and would test nothing -- dedupe is supposed to catch the case where
    the photographer held the shutter down and the subject blinked.
    """
    return Scene(
        palette=scene.palette,
        horizon=scene.horizon,
        sun_x=scene.sun_x,
        sun_r=scene.sun_r,
        ridge_seed=scene.ridge_seed,
        subjects=scene.subjects,
        grain=scene.grain + index,  # different sensor noise, same picture
        jitter=(
            rng.uniform(-0.006, 0.006),
            rng.uniform(-0.004, 0.004),
            rng.uniform(-0.02, 0.02),
        ),
    )


def _ridge(width: int, seed: int, base: float, amplitude: float, octaves: int = 3) -> np.ndarray:
    """A deterministic 1-D silhouette, in pixels from the top."""
    rng = np.random.default_rng(seed)
    x = np.linspace(0.0, 1.0, width, dtype=np.float64)
    out = np.full(width, base, dtype=np.float64)
    for octave in range(octaves):
        frequency = 1.5 * (2 ** octave) + rng.uniform(0.0, 1.5)
        phase = rng.uniform(0.0, 2 * math.pi)
        out += (amplitude / (octave + 1)) * np.sin(2 * math.pi * frequency * x + phase)
    return out


def draw_cartoon_face(draw: ImageDraw.ImageDraw, cx: float, cy: float, r: float,
                      skin: tuple[int, int, int], hair: tuple[int, int, int]) -> None:
    """A drawn cartoon head. NOT a face. See the module docstring.

    Kept deliberately crude: an oval, a hair cap, two eyes with pupils, brows,
    a nose line and a mouth. It has the coarse light/dark structure a
    face detector keys on, which is enough to tell a wired-up detector from an
    unwired one, and nothing like enough to measure one.
    """
    draw.ellipse([cx - r, cy - r * 1.22, cx + r, cy + r * 1.22], fill=skin)
    # hair cap
    draw.chord([cx - r * 1.04, cy - r * 1.34, cx + r * 1.04, cy + r * 0.5],
               start=180, end=360, fill=hair)
    eye_dx, eye_dy, eye_r = r * 0.40, r * 0.22, r * 0.19
    for side in (-1, 1):
        ex = cx + side * eye_dx
        draw.ellipse([ex - eye_r, cy - eye_dy - eye_r * 0.68,
                      ex + eye_r, cy - eye_dy + eye_r * 0.68], fill=(250, 250, 248))
        draw.ellipse([ex - eye_r * 0.42, cy - eye_dy - eye_r * 0.42,
                      ex + eye_r * 0.42, cy - eye_dy + eye_r * 0.42], fill=(32, 26, 24))
        draw.arc([ex - eye_r * 1.2, cy - eye_dy - eye_r * 1.9,
                  ex + eye_r * 1.2, cy - eye_dy - eye_r * 0.2],
                 start=200, end=340, fill=hair, width=max(1, int(r * 0.07)))
    shadow = tuple(max(0, channel - 34) for channel in skin)
    draw.line([cx, cy - r * 0.08, cx, cy + r * 0.24], fill=shadow, width=max(1, int(r * 0.09)))
    draw.arc([cx - r * 0.44, cy + r * 0.16, cx + r * 0.44, cy + r * 0.80],
             start=15, end=165, fill=(126, 62, 58), width=max(1, int(r * 0.10)))


def render(scene: Scene, width: int, height: int) -> Image.Image:
    palette = PALETTES[scene.palette]
    dx = scene.jitter[0] * width
    dy = scene.jitter[1] * height

    # Sky gradient, vectorised: a per-pixel Python loop at 1440x1080 is 1.5M
    # iterations per still and 200 stills would take minutes.
    top = np.array(palette.sky_top, dtype=np.float64)
    bottom = np.array(palette.sky_bottom, dtype=np.float64)
    ramp = np.linspace(0.0, 1.0, height, dtype=np.float64)[:, None]
    canvas = top[None, None, :] * (1.0 - ramp[:, :, None]) + bottom[None, None, :] * ramp[:, :, None]
    canvas = np.repeat(canvas, width, axis=1)

    columns = np.arange(width)[None, :]
    rows = np.arange(height)[:, None]

    # Two ridge lines then the ground, painted back to front.
    horizon_px = scene.horizon * height + dy
    for offset, colour in ((0.10, palette.hill_far), (0.035, palette.hill_near)):
        line = _ridge(width, scene.ridge_seed + int(offset * 1000),
                      horizon_px - offset * height, offset * height * 0.55)
        canvas[rows >= line[None, :]] = np.array(colour, dtype=np.float64)
    ground = np.full(width, horizon_px, dtype=np.float64)
    canvas[rows >= ground[None, :]] = np.array(palette.ground, dtype=np.float64)

    # Sun/lamp: a soft radial falloff, clipped to the sky.
    sun_x = scene.sun_x * width + dx
    sun_y = horizon_px - scene.sun_r * height * 1.4
    sun_r = scene.sun_r * width
    distance = np.sqrt((columns - sun_x) ** 2 + (rows - sun_y) ** 2)
    glow = np.clip(1.0 - distance / (sun_r * 3.2), 0.0, 1.0) ** 2
    canvas += glow[:, :, None] * (np.array(palette.sun, dtype=np.float64) - canvas) * 0.85

    # A large-scale colour cast, unique per scene and SHARED across a burst.
    #
    # This is not decoration. A 64-bit DCT pHash reads only the lowest spatial
    # frequencies, so two scenes that differ mainly in where the small subjects
    # stand can land inside the 4-bit decisive threshold and be merged as
    # duplicates. Measured: two unrelated festival_night stills came out 3 bits
    # apart and dedupe merged them, which would have made the "exactly the
    # declared bursts group" assertion untestable. Modulating the low
    # frequencies directly is what separates them; keying it to `ridge_seed`
    # keeps every frame of a burst identical in exactly the band that decides.
    tint_rng = np.random.default_rng(scene.ridge_seed ^ 0x5EED)
    u = np.linspace(0.0, 1.0, width)[None, :]
    v = np.linspace(0.0, 1.0, height)[:, None]
    cast = np.zeros((height, width), dtype=np.float64)
    for _ in range(2):
        cast += np.sin(
            2 * math.pi * (tint_rng.uniform(0.4, 1.8) * u + tint_rng.uniform(0.4, 1.8) * v)
            + tint_rng.uniform(0.0, 2 * math.pi)
        )
    channel_gain = tint_rng.uniform(-1.0, 1.0, size=3)
    canvas += 13.0 * cast[:, :, None] * channel_gain[None, None, :]

    # Grain, before the subjects so faces stay clean enough to be found at all.
    noise = np.random.default_rng(scene.grain).normal(0.0, 3.0, size=(height, width, 1))
    canvas = canvas + noise
    canvas *= 1.0 + scene.jitter[2]

    image = Image.fromarray(np.clip(canvas, 0, 255).astype(np.uint8), "RGB")
    draw = ImageDraw.Draw(image)

    for sx, sy, scale, skin_idx, hair_idx, shirt_idx in scene.subjects:
        cx = sx * width + dx
        base_y = sy * height + dy
        head_r = scale * height * 0.20
        body_h = head_r * 3.4
        body_w = head_r * 1.9
        draw.rounded_rectangle(
            [cx - body_w / 2, base_y - body_h, cx + body_w / 2, base_y],
            radius=head_r * 0.45, fill=SHIRT_TONES[shirt_idx],
        )
        draw_cartoon_face(draw, cx, base_y - body_h - head_r * 1.05, head_r,
                          SKIN_TONES[skin_idx], HAIR_TONES[hair_idx])

    return image.filter(ImageFilter.GaussianBlur(radius=0.4))


